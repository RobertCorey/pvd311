// Classify every parcel, write data/classified.csv (gitignored) and CITYWIDE.md (committed report).
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { classify, type Classification } from '../src/classify.ts';
import { loadParcels } from '../src/db.ts';
import { loadRules, type Rules, type Status } from '../src/rules.ts';
import type { Parcel } from '../src/types.ts';

const ROOT = join(import.meta.dirname, '..');
const RULES_PATH = join(ROOT, 'rules', 'ordinance-2026-04.yaml');
const STATUSES: Status[] = ['likely_covered', 'likely_exempt', 'cant_tell', 'not_residential_rental'];

// External benchmarks (see DATA_REPORT.md §7). ACS 2020–2024 5-year, Providence city (place 4459000), via Census Reporter.
const ACS = { year: 'ACS 2020–2024 5-year', housingUnits: 79423, renterOccupied: 41896, renterMoe: 1394, vacantForRent: 2746, rentedNotOccupied: 690 };
const FISCAL_NOTE = { date: '2026-02-15', author: 'Tom Sgouros', rentalUnits: 80000, covered: 48000, draft: 'January 2026 draft' };

export interface Row { p: Parcel; c: Classification; units: number; rental: number; rentalIfOwnerAbsent: number }

/** Dwelling units on the parcel and how many are (or could be) rented: an owner-occupant's own unit isn't a rental. */
export function unitCounts(p: Parcel, c: Classification, rules: Rules): Pick<Row, 'units' | 'rental' | 'rentalIfOwnerAbsent'> {
  const d = rules.data;
  const levy = d.levy_code_2_classes.includes(p.taxClass) && p.levyCode2 ? p.levyCode2 : p.levyCode;
  const oneUnitClass = p.taxClass === d.single_family_class || p.taxClass === d.condo_class;
  const units = p.units ?? (oneUnitClass ? 1 : 0);
  if (c.status === 'not_residential_rental') return { units, rental: 0, rentalIfOwnerAbsent: 0 };
  const ownerHere = d.owner_occupied_levy_codes.includes(levy) ? 1 : 0;
  const rental = Math.max(0, units - ownerHere);
  // Owner may live here (NOO rate, mail = property): rental is units - 1 if they do, units if they don't.
  const maybeOwner = c.rule === 'owner_may_live_here' ? 1 : 0;
  return { units, rental: Math.max(0, rental - maybeOwner), rentalIfOwnerAbsent: rental };
}

export function classifyAll(rules: Rules, parcels = loadParcels()): Row[] {
  return parcels.map((p) => {
    const c = classify(p, rules);
    return { p, c, ...unitCounts(p, c, rules) };
  });
}

const fmt = (n: number) => n.toLocaleString('en-US');
const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)}%` : '–');

function md(title: string, head: string[], rows: (string | number)[][]): string {
  const out = [`\n### ${title}\n`, `| ${head.join(' | ')} |`, `|${head.map((_, i) => (i ? '---:' : '---')).join('|')}|`];
  for (const r of rows) out.push(`| ${r.map((x) => (typeof x === 'number' ? fmt(x) : x)).join(' | ')} |`);
  return out.join('\n');
}

function sum(rows: Row[], f: (r: Row) => number) { return rows.reduce((a, r) => a + f(r), 0); }

function bucket(units: number): string {
  if (units <= 0) return '0 / unknown';
  if (units <= 4) return String(units);
  if (units === 5) return '5';
  if (units <= 10) return '6–10';
  if (units <= 49) return '11–49';
  return '50+';
}
const BUCKETS = ['1', '2', '3', '4', '5', '6–10', '11–49', '50+', '0 / unknown'];

function main() {
  const rules = loadRules(RULES_PATH);
  const rows = classifyAll(rules);
  const out: string[] = [];
  const total = { parcels: rows.length, units: sum(rows, (r) => r.units) };

  // CSV for spot checks / the lookup page.
  const csv = ['id,address,neighborhood,taxClass,levyCode,units,yearBuilt,ownerKind,status,rule,reason'];
  for (const r of rows) {
    csv.push([r.p.id, r.p.address, r.p.neighborhood ?? '', r.p.taxClassDesc, r.p.levyCode, r.p.units ?? '', r.p.yearBuilt ?? '', r.p.ownerKind, r.c.status, r.c.rule, r.c.reasons[0]]
      .map((v) => `"${String(v).replace(/"/g, '""')}"`).join(','));
  }
  writeFileSync(join(ROOT, 'data', 'classified.csv'), csv.join('\n'));

  out.push(`# Citywide run — ${rules.title}`);
  out.push(`\nGenerated by \`npm run citywide\` on ${new Date().toISOString().slice(0, 10)} from the FY2026 tax roll + assessor CAMA layer. Rules: \`rules/ordinance-2026-04.yaml\` (assumed effective date ${rules.assumed_effective_date}). ${fmt(total.parcels)} parcels, ${fmt(total.units)} dwelling units on record (assessor counts, incl. hotel rooms on commercial parcels).`);
  out.push(`\n"Rental units" = dwelling units minus the owner's own unit where the owner-occupied tax rate is on file. For "owner may live here" parcels the low figure assumes the owner lives there and the high figure assumes they don't.`);

  const byStatus = STATUSES.map((s) => {
    const rs = rows.filter((r) => r.c.status === s);
    return [s, rs.length, sum(rs, (r) => r.units), sum(rs, (r) => r.rental), sum(rs, (r) => r.rentalIfOwnerAbsent)];
  });
  out.push(md('By status', ['status', 'parcels', 'dwelling units', 'rental units (low)', 'rental units (high)'], byStatus as any));

  const ruleKeys = [...new Set(rows.map((r) => `${r.c.status}|${r.c.rule}`))];
  const byRule = ruleKeys.map((k) => {
    const [s, id] = k.split('|');
    const rs = rows.filter((r) => r.c.status === s && r.c.rule === id);
    return [s, id, rules.rules.find((x) => x.id === id)?.section ?? '', rs.length, sum(rs, (r) => r.units), sum(rs, (r) => r.rental)];
  }).sort((a, b) => STATUSES.indexOf(a[0] as Status) - STATUSES.indexOf(b[0] as Status) || (b[5] as number) - (a[5] as number));
  out.push(md('By deciding rule', ['status', 'rule', 'section', 'parcels', 'dwelling units', 'rental units (low)'], byRule as any));

  out.push(md('Rental units (low) by building size × status', ['units on parcel', ...STATUSES, 'covered share of known*'],
    BUCKETS.map((b) => {
      const rs = rows.filter((r) => bucket(r.units) === b);
      const v = STATUSES.map((s) => sum(rs.filter((r) => r.c.status === s), (r) => r.rental));
      return [b, ...v, pct(v[0], v[0] + v[1])];
    })));
  out.push('\n\\* covered ÷ (covered + exempt), ignoring can\'t-tell.');

  const hoods = [...new Set(rows.map((r) => r.p.neighborhood ?? '(none)'))].sort();
  const hoodRows = hoods.map((h) => {
    const rs = rows.filter((r) => (r.p.neighborhood ?? '(none)') === h);
    const v = STATUSES.slice(0, 3).map((s) => sum(rs.filter((r) => r.c.status === s), (r) => r.rental));
    return [h, ...v, pct(v[0], v[0] + v[1]), pct(v[2], v[0] + v[1] + v[2])];
  }).sort((a, b) => (b[1] as number) - (a[1] as number));
  out.push(md('Rental units (low) by neighborhood', ['neighborhood', 'likely_covered', 'likely_exempt', 'cant_tell', 'covered share of known', 'can\'t-tell share'], hoodRows));

  // Fiscal note comparison.
  const cov = rows.filter((r) => r.c.status === 'likely_covered');
  const ex = rows.filter((r) => r.c.status === 'likely_exempt');
  const ct = rows.filter((r) => r.c.status === 'cant_tell');
  const covered = sum(cov, (r) => r.rental), exempt = sum(ex, (r) => r.rental), cantLow = sum(ct, (r) => r.rental), cantHigh = sum(ct, (r) => r.rentalIfOwnerAbsent);
  const rentalLow = covered + exempt + cantLow, rentalHigh = covered + exempt + cantHigh;
  const acsRental = ACS.renterOccupied + ACS.vacantForRent + ACS.rentedNotOccupied;
  out.push(`\n## Fiscal-note comparison\n`);
  out.push(md('Covered units: this run vs. the fiscal note vs. the Census', ['measure', 'fiscal note (Feb 2026)', 'this run', 'ACS 2020–24'], [
    ['all housing units', '–', `${fmt(total.units)} on assessor record`, `${fmt(ACS.housingUnits)} ±1,256`],
    ['rental units', fmt(FISCAL_NOTE.rentalUnits), `${fmt(rentalLow)}–${fmt(rentalHigh)}`, `${fmt(ACS.renterOccupied)} renter-occupied (±${fmt(ACS.renterMoe)}); ${fmt(acsRental)} incl. vacant for rent`],
    ['covered', fmt(FISCAL_NOTE.covered), `${fmt(covered)} likely + up to ${fmt(cantHigh)} can't-tell`, '–'],
    ['covered share', pct(FISCAL_NOTE.covered, FISCAL_NOTE.rentalUnits), `${pct(covered, rentalHigh)}–${pct(covered + cantHigh, rentalHigh)}`, '–'],
  ]));

  // Sensitivity: the same data under alternative readings, by editing the rules in memory.
  const variant = (label: string, edit: (r: Rules) => void) => {
    const rr = structuredClone(rules); edit(rr);
    const rs = classifyAll(rr, rows.map((r) => r.p));
    return [label, sum(rs.filter((r) => r.c.status === 'likely_covered'), (r) => r.rental), sum(rs.filter((r) => r.c.status === 'likely_exempt'), (r) => r.rental), sum(rs.filter((r) => r.c.status === 'cant_tell'), (r) => r.rental)];
  };
  const setRule = (rr: Rules, id: string, patch: object) => Object.assign(rr.rules.find((x) => x.id === id)!, patch);
  out.push(md('Sensitivity (rental units, low)', ['reading', 'likely_covered', 'likely_exempt', 'cant_tell'], [
    variant('as passed (this run)', () => {}),
    variant('January draft size limit: owner-occupied 1–3 units', (rr) => { setRule(rr, 'owner_occupied_small_building', { max_units: 3 }); setRule(rr, 'owner_may_live_here', { max_units: 3 }); setRule(rr, 'one_additional_property', { max_units: 3 }); }),
    variant('owner-may-live-here parcels treated as owner-occupied', (rr) => setRule(rr, 'owner_may_live_here', { status: 'likely_exempt' })),
    variant('owner-may-live-here parcels treated as covered', (rr) => setRule(rr, 'owner_may_live_here', { status: 'likely_covered' })),
    variant('one-additional-property matches treated as exempt', (rr) => setRule(rr, 'one_additional_property', { status_if_match: 'likely_exempt' })),
    variant('effective date 2028-01-01 (shorter look-back reach)', (rr) => { rr.assumed_effective_date = '2028-01-01'; }),
  ]));

  writeFileSync(join(ROOT, 'CITYWIDE.md'), out.join('\n') + '\n');
  console.log(out.join('\n'));
}

if (import.meta.main) main();
