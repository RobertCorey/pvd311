#!/usr/bin/env node
// Emits public/categories.js from shared/categories.ts so the (build-less) PWA
// picker shares one source of truth with the submitter. Run: node scripts/gen-categories.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { CATEGORIES } from '../shared/categories.ts';

const ICONS = {
  pothole: '🕳️', missed_trash: '🗑️', bins_carts: '♻️', street_light: '💡',
  illegal_dumping: '🚯', abandoned_vehicle: '🚗', parking: '🅿️', animal_control: '🐾',
  unshoveled_sidewalk: '🚶', missed_plowing: '🌨️', noise: '🔊', unsure: '❓',
};

// Picker-friendly short labels (portal-facing labels stay in shared/categories.ts).
const SHORT = {
  missed_trash: 'Missed pickup', bins_carts: 'Bins & carts', illegal_dumping: 'Illegal dumping',
  abandoned_vehicle: 'Abandoned car', parking: 'Parking problem', animal_control: 'Animal issue',
};

const out = Object.entries(CATEGORIES).map(([key, c]) => ({
  key,
  label: SHORT[key] || c.label,
  icon: ICONS[key] || '📍',
  photoRequired: c.photoRequired !== false,
  seasonal: c.seasonal || null,
  extra: Object.values(c.fields || {}).map((f) => ('from' in f ? f.from.replace(/^extra\./, '') : null)).filter(Boolean),
}));

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const body = `// GENERATED by scripts/gen-categories.mjs from shared/categories.ts — do not edit.\nwindow.PVD_CATEGORIES = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync(join(root, 'public', 'categories.js'), body);
console.log(`wrote public/categories.js (${out.length} categories)`);
